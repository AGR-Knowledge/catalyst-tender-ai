/**
 * The tender library's view models (plan 030). A library is a tree of folders
 * holding files; each file says what it is, where it came from, when and from
 * whom, and how the file viewer shows it. Everything here is derived from data
 * the demo already has (`libraryFor`); the only new state is the files people
 * add (`uploads.ts`).
 *
 * `FileViewer` (components/tender) takes these, so plan 031's supplier
 * documents use the same shapes: keep them backward compatible.
 */

/** The type tag on a file's row. */
export type FileTypeTag = 'PDF' | 'CSV' | 'Letter' | 'Email' | 'Form' | 'Record' | 'Image' | 'File';

/** How a file reached the company, or who made it. */
export type SourceChannel = 'portal' | 'email' | 'scan' | 'upload' | 'authority' | 'agent' | 'person' | 'supplier' | 'vault' | 'added';

export interface FileSourceVM {
  channel: SourceChannel;
  /** In words: "Etimad", "Email to tenders@…", "Scanned drop", "Generated by the Bid Strategy agent". */
  label: string;
}

/**
 * How View shows the file:
 * - `url`: a PDF the demo holds, in the browser's own viewer;
 * - `html`: a document facsimile (`facsimileHtml`), built only when viewed;
 * - `csv`: a CSV the demo holds, shown as a plain table (`csvHtml`);
 * - `added`: a file someone added in the demo. `src()` is its object URL in the
 *   session that added it, or null after a reload (the demo keeps its details, not its content).
 */
export type FileViewVM =
  | { kind: 'url'; src: string }
  | { kind: 'html'; html(): string }
  | { kind: 'csv'; src: string }
  | { kind: 'added'; mime: string; bytes: number; at: string; byName: string; src(): string | null };

export interface LibraryFileVM {
  /** Unique in the library: the folder id and the file name. */
  id: string;
  /** The file name, e.g. "SRRWD-2026-128 Letter of invitation.pdf". */
  name: string;
  /** What it is, in words: "Letter of invitation". */
  title: string;
  /** A stable key for what the file is, for checks and row extras: 'notice', 'booklet', 'boq', 'addendum', 'rfq', 'quote', 'added' … */
  kind?: string;
  type: FileTypeTag;
  /** Set when the document is not in English only. */
  lang?: 'AR' | 'EN+AR';
  /** Some pages are scanned images read by OCR. */
  scanned?: boolean;
  /** The pages read by OCR, in words ("pp. 15–17"), when known. */
  ocrText?: string;
  source: FileSourceVM;
  /** Tenant-local `YYYY-MM-DDTHH:MM` (or a date). Null when the data has no time. */
  receivedAt: string | null;
  /** A person's name, or the issuing body. */
  by: string | null;
  /** Pages or rows, when known. */
  extent?: { n: number; unit: 'page' | 'row' };
  /** Further tags on the row: "Duplicate of …", "v2", "Added by …". */
  tags: string[];
  /** Listed, but its figures are masked in the facsimile: who can see them. */
  masked?: { by: string } | null;
  view: FileViewVM;
  /** A screen that holds the live record, e.g. Company › Credentials. */
  link?: { to: string; label: string };
  /** The folder it sits in, and the folder names from the root: ["01 Tender documents", "Addenda"]. */
  folderId: string;
  path: string[];
}

export interface LibraryFolderVM {
  id: string;
  /** "01 Tender documents", "Addenda". */
  name: string;
  /** Folder names from the root, this one last. */
  path: string[];
  files: LibraryFileVM[];
  folders: LibraryFolderVM[];
  /** Files in this folder and below, including masked ones. */
  count: number;
  /** The folder is listed with its count only: who can see its files. */
  masked?: { by: string } | null;
  /** People may add files here. */
  addable?: boolean;
}

export interface LibraryVM {
  tenderId: string;
  folders: LibraryFolderVM[];
  /** Every file the viewer may see, in folder order. */
  files: LibraryFileVM[];
  /** Files in every folder, masked ones included. */
  count: number;
  /** Folders that hold a file, at any depth. */
  folderCount: number;
}
